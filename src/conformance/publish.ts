// The published support matrix (docs/support-matrix.md), rendered from the recorded conformance results. It is
// regenerated with `npm run conformance -- matrix --write` and a test fails when the file is stale.

import { matrixOf, renderMatrix } from "./matrix.ts";
import { OS_LABELS, SUITE_VERSION, type ConformanceResult } from "./result.ts";

/** The adapters of release 1, listed even when no result is recorded for one. */
export const RELEASE_ADAPTERS = ["claude-code", "codex", "opencode"] as const;

/** The systems core CI runs on (`.github/workflows/ci.yml`, the mock adapter only), by the label the matrix uses. */
export const CORE_CI_SYSTEMS = [
  { label: "Windows", runner: "windows-latest" },
  { label: "Linux", runner: "ubuntu-latest" },
  { label: "macOS", runner: "macos-latest" },
] as const;

export function renderSupportMatrixDoc(results: readonly ConformanceResult[]): string {
  const core = [
    "| System | CI runner | Core (protocol, ledger, runtime, evaluation) |",
    "| --- | --- | --- |",
    ...CORE_CI_SYSTEMS.map(({ label, runner }) => `| ${label} | \`${runner}\` | typecheck, tests and build pass in CI |`),
  ];
  const cells = matrixOf(results, RELEASE_ADAPTERS);
  return `<!-- Generated by \`npm run conformance -- matrix --write\` from conformance/results/. Do not edit by hand. -->
# Support matrix

Two different things are tested, and they are published apart.

## Core, by operating system

The core runs in CI on each system below with **the mock adapter only**: no coding-agent CLI is installed there and no credential exists. A mock result says the core works on that system and says nothing about any real tool.

${core.join("\n")}

## Adapters, by operating system

Each cell is the latest conformance result recorded for that adapter on that system (\`conformance/results/\`), with the tool version and the date it was run. The suite (version ${SUITE_VERSION}) is run by the maintainer under their own logins, never in CI.

${renderMatrix(cells)}

How to read it:

- **passed**: every check of the current suite ran and passed. A check the suite cannot make the tool do (a rate limit, a tool that reports no model or no usage) is skipped, never passed, so such an adapter cannot reach \`passed\`.
- **untested**: no result is recorded, the result is from an older suite, or at least one check was skipped (the cell says which). It does not mean the adapter fails there, and it does not mean it works.
- **failed**: a check failed; the cell names it.
- Columns are the systems the maintainer can name: ${OS_LABELS.join(", ")}. The maintainer develops on Windows and runs Linux through WSL2. **No adapter has been tested on macOS or on native Linux**, so those cells are untested whatever the core CI says.
- A level of enforcement (\`enforced_by_tool\`, \`cooperative\`, \`none\`) is a separate, per-adapter declaration; see each adapter's page under [adapters](adapters/). Only a conformance probe that holds counts as enforcement.

See [limits](limits.md) for what AHP does not protect against.
`;
}
